#!/usr/bin/env python3
"""Stage the Thunder Dragon / Abyss gacha content on top of client 1.4.78.

The shared release was built against another version line and contains full
copies of several master tables.  Installing those copies directly would drop
locally-owned characters, shops and the Fantasy equipment ``trimmed_image``
rows.  This importer therefore treats ``ownership.json`` as a whitelist:

* the current 1.4.78 archive chain is the base;
* only explicitly-owned outer orderedmap keys are appended;
* all unrelated rows remain byte-for-byte identical;
* genuinely new resources are staged unchanged;
* the two shared item-atlas replacements are accepted only when the current
  base and incoming hashes match the reviewed release.

The output is an ignored working store, not a published diff archive.  The
active manifest and ``.cdn`` are read-only and are never modified.
"""

