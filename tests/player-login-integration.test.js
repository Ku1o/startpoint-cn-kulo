    const code = auth.createPlayerLoginCode(other.viewer, 'bind')
    const codePreview = auth.previewPlayerClaim({ code: code.code })
    const byCode = auth.bindPlayerLogin(codePreview.proof, 'CodeUserA', 'CodePass7', true)
