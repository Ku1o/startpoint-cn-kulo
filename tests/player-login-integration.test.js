    auth.resetPlayerLoginPassword(reset.code, 'ResetPlain8')
    check(!auth.readPlayerLoginSession(bound.token), 'password reset revokes every previous session')
    assert.throws(() => auth.resetPlayerLoginPassword(reset.code, 'ResetPlain9'), auth.PlayerLoginError)
    const afterReset = auth.loginPlayer('oldsavea', 'ResetPlain8', true)
    check(afterReset.profile.viewer_id === old.viewer, 'reset preserves original save')
    check(!auth.playerSocketAllowed(old.viewer, '') && auth.playerSocketAllowed(old.viewer, afterReset.token), 'managed TCP handshake requires session')
    db.prepare("UPDATE accounts SET status='banned' WHERE id=?").run(old.account.id)
